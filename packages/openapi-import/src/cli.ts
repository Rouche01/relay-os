#!/usr/bin/env node
/**
 * OpenAPI 3 → Relay ServiceDescriptor YAML
 *
 *   pnpm --filter @relay/openapi-import exec relay-openapi-import \
 *     --input ./fixtures/github-issues.openapi.json \
 *     --id github \
 *     --operations issuesListForRepo,issuesCreateComment \
 *     --out ../../apps/triage-gen/services/github.yaml
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { parseArgs } from "node:util";
import {
  emitServiceDescriptorYaml,
  listOpenApiOperations,
  loadOpenApiFile,
  openApiToServiceDescriptor,
  type AuthOverride,
} from "./index.js";

function usage(): string {
  return `Usage: relay-openapi-import --input <file> --id <serviceId> [options]

Options:
  --input, -i       OpenAPI 3 JSON/YAML file (required)
  --id              ServiceDescriptor id (required unless --list)
  --operations, -o  Comma-separated operationIds to import
  --tags            Comma-separated OpenAPI tags filter
  --all             Import every operation (use with care)
  --out, -O         Write YAML to this path (default: stdout)
  --base-url        Override servers[0].url
  --title           Override info.title
  --description     Override info.description
  --auth            auto | none | bearer | apiKey:HeaderName (default: auto)
  --list            List operationId method path (no convert)
  --help, -h        Show help
`;
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      input: { type: "string", short: "i" },
      id: { type: "string" },
      operations: { type: "string", short: "o" },
      tags: { type: "string" },
      all: { type: "boolean", default: false },
      out: { type: "string", short: "O" },
      "base-url": { type: "string" },
      title: { type: "string" },
      description: { type: "string" },
      auth: { type: "string", default: "auto" },
      list: { type: "boolean", default: false },
      help: { type: "boolean", short: "h", default: false },
    },
    allowPositionals: false,
  });

  if (values.help) {
    process.stdout.write(usage());
    return;
  }
  if (!values.input) {
    process.stderr.write(usage());
    process.exitCode = 1;
    return;
  }

  const inputPath = resolve(values.input);
  const doc = loadOpenApiFile(inputPath);

  if (values.list) {
    const rows = listOpenApiOperations(doc);
    for (const r of rows) {
      const tags = r.tags.length ? ` [${r.tags.join(",")}]` : "";
      process.stdout.write(
        `${r.operationId}\t${r.method}\t${r.path}${tags}\n`
      );
    }
    process.stderr.write(`# ${rows.length} operation(s)\n`);
    return;
  }

  if (!values.id?.trim()) {
    process.stderr.write("--id is required (unless --list)\n");
    process.exitCode = 1;
    return;
  }

  const operations = values.operations
    ? values.operations
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
    : undefined;
  const tags = values.tags
    ? values.tags
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
    : undefined;

  const descriptor = openApiToServiceDescriptor(doc, {
    id: values.id,
    title: values.title,
    description: values.description,
    baseUrl: values["base-url"],
    operations,
    tags,
    keepAll: values.all === true,
    auth: (values.auth ?? "auto") as AuthOverride,
    markWritesIrreversible: true,
  });

  const yaml = emitServiceDescriptorYaml(descriptor, {
    headerComments: [
      `Generated by @relay/openapi-import from ${values.input}`,
      "Do not edit by hand — re-run the importer. Secrets never live here.",
    ],
  });

  if (values.out) {
    const outPath = resolve(values.out);
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, yaml, "utf8");
    process.stderr.write(
      `Wrote ${descriptor.operations.length} operation(s) → ${outPath}\n`
    );
  } else {
    process.stdout.write(yaml);
  }
}

main().catch((err) => {
  process.stderr.write(
    `${err instanceof Error ? err.message : String(err)}\n`
  );
  process.exitCode = 1;
});
